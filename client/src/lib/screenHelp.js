export function helpFor(pathname) {
  const path = pathname.replace(/\/$/, '') || '/pms';
  const key = Object.keys(SCREEN_HELP).filter((k) => path === k || path.startsWith(`${k}/`)).sort((a, b) => b.length - a.length)[0];
  return key ? SCREEN_HELP[key] : GENERAL_HELP;
}
